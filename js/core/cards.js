export const CARD_BY_ID = Object.fromEntries(CARDS.map((c) => [c.id, c]));

export const KEYWORD_TEXT = {
  guard: 'Guardián',
  swift: 'Ímpetu',
  shield: 'Escudo',
  drain: 'Vampírico',
  poison: 'Letal',
  stealth: 'Sigilo',
  fury: 'Furia',
};

const TARGET_TEXT = { enemy: 'a un enemigo', enemyUnit: 'a una criatura enemiga', allyUnit: 'a una criatura aliada' };
const TRIGGER_TEXT = { play: 'Al jugarla: ', death: 'Al morir: ', spell: 'Cuando lanzas un hechizo: ', turnEnd: 'Al final de tu turno: ', attack: 'Al atacar: ' };

// Texto de reglas legible, generado a partir de los datos (una sola fuente de verdad).
// Plural de la primera palabra («Autómatas de Bronce», «Murciélagos Vampiro»); basta para los nombres de fichas.
const plural = (name = '') => name.replace(/^(\S+)/, (w) => (/[aeiouáéó]$/i.test(w) ? w + 's' : w + 'es'));

function effectBody(card, e, t) {
  return {
    damage: `inflige ${e.amount} de daño ${t}`,
    damageAllEnemies: `inflige ${e.amount} de daño a todas las criaturas enemigas`,
    damageHero: `inflige ${e.amount} de daño al héroe enemigo`,
    heal: `cura ${e.amount} a tu héroe`,
    draw: `roba ${e.amount} carta${e.amount > 1 ? 's' : ''}`,
    shield: `da Escudo ${t}`,
    buff: `da +${e.amount}/+${e.amount} ${t}`,
    summon: `invoca ${e.amount} ${e.amount > 1 ? plural(CARD_BY_ID[e.token]?.name ?? e.token) : CARD_BY_ID[e.token]?.name ?? e.token} ${CARD_BY_ID[e.token]?.atk}/${CARD_BY_ID[e.token]?.hp}${CARD_BY_ID[e.token]?.keywords ? ` (${CARD_BY_ID[e.token].keywords.map((k) => KEYWORD_TEXT[k]).join(', ')})` : ''}`,
    growPerAlly: `gana +${e.amount}/+${e.amount} por cada otra criatura aliada`,
    buffSelf: `gana +${e.amount} de ataque`,
    damageAll: `inflige ${e.amount} de daño a TODAS las criaturas`,
    destroy: `destruye ${t}`,
    freeze: `congela ${t} (no podrá atacar en su próximo turno)`,
    buffAll: `da +${e.amount}/+${e.amount} a tus ${card.type === 'unit' ? 'otras ' : ''}criaturas`,
    energy: `ganas ${e.amount} de energía este turno`,
    damageHeal: `inflige ${e.amount} de daño ${t} y cura ${e.amount} a tu héroe`,
    bounce: `devuelve ${t} a la mano de su dueño`,
    silence: `silencia ${t} (pierde sus palabras clave y su efecto)`,
    silenceAll: 'silencia a todas las criaturas enemigas',
    grant: `da ${KEYWORD_TEXT[e.keyword]} ${t}`,
    freezeAll: 'congela a todas las criaturas enemigas',
    shieldAll: `da Escudo a tus ${card.type === 'unit' ? 'otras ' : ''}criaturas`,
    weaken: `quita ${e.amount} de ataque ${t}`,
    addCard: `añade ${e.amount > 1 ? `${e.amount} cartas de ` : 'la carta '}${CARD_BY_ID[e.card]?.name} a tu mano`,
    missiles: e.amount > 1 ? `lanza ${e.amount} proyectiles de 1 de daño contra enemigos al azar` : 'inflige 1 de daño a un enemigo al azar',
    hurtSelf: `recibes ${e.amount} de daño`,
    transform: `transforma ${t} en ${CARD_BY_ID[e.token]?.name} ${CARD_BY_ID[e.token]?.atk}/${CARD_BY_ID[e.token]?.hp}`,
  }[e.kind];
}

export function cardText(card) {
  const parts = (card.keywords || []).map((k) => KEYWORD_TEXT[k]);
  const e = card.effect;
  if (e) {
    const t = TARGET_TEXT[e.target] || '';
    // "then" actúa sobre el mismo objetivo que el efecto principal.
    const body = effectBody(card, e, t) + (e.then ? ` y ${effectBody(card, e.then, e.target === 'enemy' ? 'al mismo objetivo' : 'a esa criatura')}` : '');
    const text = (TRIGGER_TEXT[e.trigger] || '') + body;
    parts.push(text.charAt(0).toUpperCase() + text.slice(1) + '.');
  }
  return parts.join('. ');
}
